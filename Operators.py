#Operatots
print("Операторы")
Num1 = 5
Num2 = 10
# +
print(f"{Num1} + {Num2} =", Num1 + Num2)
# -
print(f"{Num2} - {Num1} =", Num2 - Num1)
# *
print(f"{Num1} * {Num2} =", Num1 * Num2)
# /
print(f"{Num2} / {Num1} =", Num2 / Num1)
# %
print(f"{Num2} % {Num1} =", Num2 % Num1)
# **
print(f"{Num2} ** {Num1} =", Num2 ** Num1)
# //
print(f"{Num2} // {Num1} =", Num2 // Num1)